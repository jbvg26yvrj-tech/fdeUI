import { beforeEach, expect, it, vi } from 'vitest';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import ChangeDatacenterPage from './ChangeDatacenterPage';
import { ApiError } from '../../../shared/api/ApiError';
const mocks = vi.hoisted(() => ({ fetch: vi.fn(), schedule: vi.fn(), change: vi.fn(), toast: vi.fn(), tableChange: vi.fn() }));
vi.mock('react-router', () => ({ useNavigate: () => vi.fn() }));
vi.mock('sonner', () => ({ toast: { error: mocks.toast, success: vi.fn() } }));
vi.mock('../../../features/pipeline/pipelines-table/api/pipelinesTableApi', () => ({ fetchPipelines: mocks.fetch, mapServerResponseToTableMeta: vi.fn() }));
vi.mock('../../../features/pipeline/api/schedulesApi', () => ({ schedulesApi: { getSchedule: mocks.schedule } }));
vi.mock('../../../features/pipeline/api/pipelinesCrudApi', () => ({ pipelinesCrudApi: { bulkChangeDatacenter: mocks.change } }));
vi.mock('../../../shared/ui/table/hooks/useTableData', () => ({ useTableData: () => ({ data: [{ id: 'a', pipelineName: 'Alpha' }], isLoading: false, serverMeta: { pagination: { page: 0, size: 20, totalElements: 2, totalPages: 1 } }, handleTableChange: mocks.tableChange, loadServerData: vi.fn() }) }));
vi.mock('../../../shared/ui/table/components/TableStates', () => ({ TableWithStates: ({ children }: any) => children }));
vi.mock('../../../shared/ui/table/Table', () => ({ default: ({ onTableChange }: any) => <button onClick={() => onTableChange({ pagination: { page: 1, size: 20 }, filters: { clientFrom: 'changed' }, sort: null })}>Filter</button> }));
vi.mock('./StepProgressModal', () => ({ default: () => null }));
vi.mock('../../../shared/components/ConfirmationModal', () => ({ ConfirmationModal: ({ isOpen, message }: any) => isOpen ? <div role='dialog'>{message}</div> : null }));
beforeEach(() => { vi.clearAllMocks(); });
it('selects the page, clears selection on filter change and offers every requested page size', () => {
  render(<ChangeDatacenterPage />);
  const action = screen.getByRole('button', { name: 'Сменить ЦОД' });
  expect(action).toBeDisabled();
  fireEvent.click(screen.getByText('Выбрать все на странице'));
  expect(action).toBeEnabled();
  fireEvent.click(screen.getByText('Filter'));
  expect(action).toBeDisabled();
  expect([...screen.getByLabelText('Маршрутов на странице').querySelectorAll('option')].map(o => o.value)).toEqual(['20', '50', '100', '200']);
  fireEvent.change(screen.getByLabelText('Маршрутов на странице'), { target: { value: '200' } });
  expect(mocks.tableChange).toHaveBeenLastCalledWith(expect.objectContaining({ pagination: { page: 1, size: 200 } }));
});
it('cancels collection and ignores its late result while preserving explicit selection', async () => {
  let finish!: (value: any) => void;
  mocks.fetch.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  render(<ChangeDatacenterPage />);
  fireEvent.click(screen.getByText('Выбрать все на странице'));
  fireEvent.click(screen.getByText('Выбрать все 2 по фильтрам'));
  expect(screen.getByRole('button', { name: 'Сменить ЦОД' })).toBeDisabled();
  fireEvent.click(screen.getByText('Отменить сбор'));
  finish({ content: [{ id: 'b' }, { id: 'c' }], totalElements: 2 });
  await waitFor(() => expect(screen.queryByRole('status')).not.toBeInTheDocument());
  expect(screen.getByText('1')).toBeInTheDocument();
  expect(mocks.fetch).toHaveBeenCalledTimes(1);
});
it('does not open the wizard or mutate anything after schedule lookup fails', async () => {
  mocks.schedule.mockRejectedValue(new ApiError('unavailable', 500));
  render(<ChangeDatacenterPage />);
  fireEvent.click(screen.getByText('Выбрать все на странице'));
  fireEvent.click(screen.getByRole('button', { name: 'Сменить ЦОД' }));
  await waitFor(() => expect(mocks.toast).toHaveBeenCalled());
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
  expect(mocks.change).not.toHaveBeenCalled();
});
